pub fn format_tracker_element_label(element: &str) -> String {
    match element.trim().to_ascii_lowercase().as_str() {
        "img" => "Image (<img>)".to_string(),
        "srcset" => "Responsive Image (srcset)".to_string(),
        "background" => "CSS Background Image".to_string(),
        "link" => "Prefetch / Stylesheet (<link>)".to_string(),
        "a" | "href" => "Tracked Hyperlink (<a>)".to_string(),
        other if other.is_empty() => "HTML Element".to_string(),
        other => other.to_string(),
    }
}

pub fn format_tracker_reason_label(reason: &str) -> String {
    match reason.trim().to_ascii_lowercase().as_str() {
        "domain" => "Known tracker domain".to_string(),
        "tiny" => "1x1 / Hidden spy pixel".to_string(),
        "pattern" => "Tracking URL signature".to_string(),
        "pixel" => "Invisible web beacon".to_string(),
        other if other.is_empty() => "Heuristic tracker match".to_string(),
        other => other.to_string(),
    }
}

pub fn lookup_tracker_vendor(domain: &str) -> TrackerVendorProfile {
    let lower = domain.trim().to_ascii_lowercase();
    for (pat, vendor, cat, sev, desc) in KNOWN_TRACKER_VENDORS {
        if lower == *pat || lower.ends_with(&format!(".{}", pat)) || lower.contains(pat) {
            return TrackerVendorProfile {
                pattern: (*pat).to_string(),
                vendor_name: (*vendor).to_string(),
                category: (*cat).to_string(),
                severity: (*sev).to_string(),
                description: (*desc).to_string(),
            };
        }
    }

    TrackerVendorProfile {
        pattern: lower.clone(),
        vendor_name: "Unclassified Tracking Endpoint".to_string(),
        category: "Remote Telemetry / Web Beacon".to_string(),
        severity: "Medium".to_string(),
        description:
            "External resource stripped by Mailx to prevent sender IP, timestamp, and user-agent leakage."
                .to_string(),
    }
}

pub fn enrich_tracker_item(item: &RemovedTrackerItem) -> EnrichedTrackerFinding {
    let vendor = lookup_tracker_vendor(&item.domain);
    let element_label = format_tracker_element_label(&item.element);
    let reason_label = format_tracker_reason_label(&item.reason);

    let severity = if item.reason.eq_ignore_ascii_case("tiny") && vendor.severity == "Medium" {
        "High".to_string()
    } else {
        vendor.severity.clone()
    };

    EnrichedTrackerFinding {
        domain: item.domain.clone(),
        element: item.element.clone(),
        element_label,
        reason: item.reason.clone(),
        reason_label,
        vendor_name: vendor.vendor_name,
        category: vendor.category,
        severity,
        technical_summary: vendor.description,
    }
}

pub fn audit_trackers_report(report: &TrackersReport) -> EnrichedTrackersAudit {
    let mut high_severity_count = 0usize;
    let mut pixel_beacon_count = 0usize;
    let mut link_redirect_count = 0usize;
    let mut unique_domains: Vec<String> = Vec::new();
    let mut findings = Vec::with_capacity(report.trackers.len());

    for item in &report.trackers {
        let dom = item.domain.trim().to_ascii_lowercase();
        if !dom.is_empty() && !unique_domains.contains(&dom) {
            unique_domains.push(dom);
        }
        let enriched = enrich_tracker_item(item);
        if matches!(enriched.severity.as_str(), "Critical" | "High") {
            high_severity_count += 1;
        }
        if matches!(
            item.element.trim().to_ascii_lowercase().as_str(),
            "img" | "srcset" | "background"
        ) || item.reason.eq_ignore_ascii_case("tiny")
        {
            pixel_beacon_count += 1;
        } else {
            link_redirect_count += 1;
        }
        findings.push(enriched);
    }

    EnrichedTrackersAudit {
        total_removed: report.total,
        high_severity_count,
        pixel_beacon_count,
        link_redirect_count,
        unique_domains,
        findings,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_vendor_lookup_and_audit() {
        let report = TrackersReport {
            total: 2,
            trackers: vec![
                RemovedTrackerItem {
                    domain: "t.hubspot.com".to_string(),
                    element: "img".to_string(),
                    reason: "tiny".to_string(),
                },
                RemovedTrackerItem {
                    domain: "list-manage.com".to_string(),
                    element: "a".to_string(),
                    reason: "domain".to_string(),
                },
            ],
        };
        let audit = audit_trackers_report(&report);
        assert_eq!(audit.total_removed, 2);
        assert_eq!(audit.high_severity_count, 2);
        assert_eq!(audit.findings[0].vendor_name, "HubSpot CRM");
        assert_eq!(audit.findings[1].vendor_name, "Intuit Mailchimp");
    }
}
